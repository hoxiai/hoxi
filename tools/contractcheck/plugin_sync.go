const pluginGeneratedBanner = "// Code generated by esbuild from browser_plugin.js; DO NOT EDIT."

var (
	bareHTTPHelpers = map[string]bool{
		"Get":      true,
		"Head":     true,
		"Post":     true,
		"PostForm": true,
	}
	jsImportRe       = regexp.MustCompile(`(?m)^\s*(?:import|export)\s+(?:[^"']*?\s+from\s+)?["'](\.[^"']+)["']`)
	jsIndexActionsRe = regexp.MustCompile(`const\s+indexActions\s*=\s*\[([^\]]+)\]`)
	jsQuotedTokenRe  = regexp.MustCompile(`"([^"]+)"`)
	jsSensitiveSetRe = regexp.MustCompile(`const\s+SENSITIVE_BASENAMES\s*=\s*new\s+Set\(\[([\s\S]*?)\]\)`)
	jsPluginToolsRe  = regexp.MustCompile(`tool:\s*\{([\s\S]*?)\}\s*,\s*"experimental\.chat\.system\.transform"`)
	jsObjectKeyRe    = regexp.MustCompile(`\b(hoxi_[a-z0-9_]+|goal_report)\s*:`)
)

func checkInternalASTContracts(fset *token.FileSet, file *ast.File, rel, baseName, pkg string) []Violation {
	var violations []Violation

	httpAliases := make(map[string]bool)
	for _, imp := range file.Imports {
		impPath, err := strconv.Unquote(imp.Path.Value)
		if err != nil || impPath != "net/http" {
			continue
		}
		switch {
		case imp.Name == nil:
			httpAliases["http"] = true
		case imp.Name.Name == ".":
			p := fset.Position(imp.Pos())
			violations = append(violations, Violation{
				Rule:    "http-client",
				File:    rel,
				Line:    p.Line,
				Col:     p.Column,
				Message: "dot-import of net/http is forbidden; use explicit package qualifier",
			})
		case imp.Name.Name != "_":
			httpAliases[imp.Name.Name] = true
		}
	}

	isProviderPkg := pkg == "provider"
	checkEndpoints := !isProviderPkg && rel != "internal/handoff/grok_bridge.go"

	ast.Inspect(file, func(n ast.Node) bool {
		if n == nil {
			return false
		}
		switch node := n.(type) {
		case *ast.TypeSpec:
			if node.Assign.IsValid() && node.Name != nil && node.Name.Name == "desktopGateway" {
				p := fset.Position(node.Pos())
				violations = append(violations, Violation{
					Rule:    "boundary-alias",
					File:    rel,
					Line:    p.Line,
					Col:     p.Column,
					Message: "legacy 'type desktopGateway =' alias is forbidden; use explicit *Service or *Gateway receiver",
				})
			}

		case *ast.Ident:
			if rel == "internal/gateway/tunnel.go" && node.Name == "tunnelRoutePrefixes" {
				p := fset.Position(node.Pos())
				violations = append(violations, Violation{
					Rule:    "tunnel-guard",
					File:    rel,
					Line:    p.Line,
					Col:     p.Column,
					Message: "prefix-based tunnelRoutePrefixes is forbidden; declare explicit (method, pattern) entries in tunnelRoutes",
				})
			}

		case *ast.BasicLit:
			if checkEndpoints && node.Kind == token.STRING {
				if lit, err := strconv.Unquote(node.Value); err == nil {
					if lit == "/v1/messages" || lit == "/chat/completions" {
						p := fset.Position(node.Pos())
						violations = append(violations, Violation{
							Rule:    "llm-endpoint-boundary",
							File:    rel,
							Line:    p.Line,
							Col:     p.Column,
							Message: fmt.Sprintf("hand-rolled %q endpoint outside internal/provider is forbidden; route via internal/llm and internal/provider", lit),
						})
					}
				}
			}

		case *ast.SelectorExpr:
			if len(httpAliases) == 0 {
				return true
			}
			pkgIdent, ok := node.X.(*ast.Ident)
			if !ok || !httpAliases[pkgIdent.Name] || node.Sel == nil {
				return true
			}
			sel := node.Sel.Name
			if bareHTTPHelpers[sel] {
				p := fset.Position(node.Pos())
				violations = append(violations, Violation{
					Rule:    "http-client",
					File:    rel,
					Line:    p.Line,
					Col:     p.Column,
					Message: fmt.Sprintf("%s.%s bypasses explicit timeout and transport controls; construct an explicit http.RequestWithContext", pkgIdent.Name, sel),
				})
			}
			if isProviderPkg && (sel == "DefaultClient" || sel == "DefaultTransport") {
				p := fset.Position(node.Pos())
				violations = append(violations, Violation{
					Rule:    "provider-http-client",
					File:    rel,
					Line:    p.Line,
					Col:     p.Column,
					Message: fmt.Sprintf("%s.%s is forbidden in internal/provider; use explicit providerTransport, localTransport, or safeVideoRoundTripper", pkgIdent.Name, sel),
				})
			}

		case *ast.CallExpr:
			if !isProviderPkg || len(httpAliases) == 0 {
				return true
			}
			if fn, ok := node.Fun.(*ast.Ident); ok && fn.Name == "new" && len(node.Args) == 1 {
				if isHTTPClientTypeExpr(node.Args[0], httpAliases) {
					p := fset.Position(node.Pos())
					violations = append(violations, Violation{
						Rule:    "provider-http-client",
						File:    rel,
						Line:    p.Line,
						Col:     p.Column,
						Message: "new(http.Client) without explicit Transport is forbidden in internal/provider",
					})
				}
			}

		case *ast.ValueSpec:
			if !isProviderPkg || len(httpAliases) == 0 || node.Type == nil {
				return true
			}
			// Catch `var c http.Client` (zero-value struct without explicit Transport).
			if isHTTPClientTypeExpr(node.Type, httpAliases) && len(node.Values) == 0 {
				p := fset.Position(node.Pos())
				violations = append(violations, Violation{
					Rule:    "provider-http-client",
					File:    rel,
					Line:    p.Line,
					Col:     p.Column,
					Message: "zero-value var http.Client without explicit Transport is forbidden in internal/provider",
				})
			}

		case *ast.CompositeLit:
			if !isProviderPkg || len(httpAliases) == 0 || !isHTTPClientTypeExpr(node.Type, httpAliases) {
				return true
			}
			p := fset.Position(node.Pos())
			if !providerTransportAllowlist[baseName] {
				violations = append(violations, Violation{
					Rule: "provider-http-client",
					File: rel,
					Line: p.Line,
					Col:  p.Column,
					Message: fmt.Sprintf(
						"constructing http.Client in %s is forbidden; reuse callSimpleLLM, newSafeVideoHTTPClient, or selectImageTransport via an authorized provider transport file",
						rel,
					),
				})
				return true
			}
			if !compositeHasNonNilField(node, "Transport") {
				violations = append(violations, Violation{
					Rule:    "provider-http-client",
					File:    rel,
					Line:    p.Line,
					Col:     p.Column,
					Message: "http.Client literal in internal/provider must explicitly set a non-nil Transport field",
				})
			}
		}
		return true
	})

	return violations
}

func isHTTPClientTypeExpr(expr ast.Expr, httpAliases map[string]bool) bool {
	sel, ok := expr.(*ast.SelectorExpr)
	if !ok || sel.Sel == nil || sel.Sel.Name != "Client" {
		return false
	}
	pkgIdent, ok := sel.X.(*ast.Ident)
	return ok && httpAliases[pkgIdent.Name]
}

func compositeHasNonNilField(lit *ast.CompositeLit, fieldName string) bool {
	for _, elt := range lit.Elts {
		kv, ok := elt.(*ast.KeyValueExpr)
		if !ok {
			continue
		}
		keyIdent, ok := kv.Key.(*ast.Ident)
		if !ok || keyIdent.Name != fieldName {
			continue
		}
		if ident, isIdent := kv.Value.(*ast.Ident); isIdent && ident.Name == "nil" {
			return false
		}
		return true
	}
	return false
}

func checkBrowserPluginSync(repoRoot string) ([]Violation, int, string) {
	const (
		entryRel  = "internal/opencode/browser_plugin.js"
		bundleRel = "internal/opencode/browser_plugin.mjs"
	)
	entryPath := filepath.Join(repoRoot, filepath.FromSlash(entryRel))
	bundlePath := filepath.Join(repoRoot, filepath.FromSlash(bundleRel))

	var violations []Violation
	if _, err := os.Stat(entryPath); err != nil {
		violations = append(violations, Violation{
			Rule:    "plugin-sync",
			File:    entryRel,
			Message: "missing browser plugin source entrypoint internal/opencode/browser_plugin.js",
		})
		return violations, 0, "missing"
	}

	bundleBytes, err := os.ReadFile(bundlePath)
	if err != nil {
		violations = append(violations, Violation{
			Rule:    "plugin-sync",
			File:    bundleRel,
			Message: "missing embedded bundle internal/opencode/browser_plugin.mjs",
		})
		return violations, 0, "missing"
	}

	normBundle := normalizeLF(bundleBytes)
	if !bytes.HasPrefix(normBundle, []byte(pluginGeneratedBanner+"\n")) {
		violations = append(violations, Violation{
			Rule:    "plugin-sync",
			File:    bundleRel,
			Line:    1,
			Message: fmt.Sprintf("bundle must start with %q", pluginGeneratedBanner),
		})
	}

	moduleContents, missingViolations := collectPluginSourceClosure(repoRoot, entryRel)
	violations = append(violations, missingViolations...)

	for _, requiredRel := range []string{
		"web/src/policy/permission-policy.js",
		"web/src/policy/external-path-risk.js",
		"internal/opencode/hoxi_plugin.js",
		"internal/opencode/code_index_tool.js",
	} {
		if _, ok := moduleContents[requiredRel]; !ok {
			violations = append(violations, Violation{
				Rule:    "plugin-sync",
				File:    entryRel,
				Message: fmt.Sprintf("browser_plugin.js dependency closure no longer imports canonical module %s", requiredRel),
			})
		}
	}

	violations = append(violations, verifyPluginSemanticTokens(bundleRel, string(normBundle), moduleContents)...)

	esbuildBin := resolveLocalEsbuild(repoRoot)
	if esbuildBin == "" {
		return violations, len(moduleContents), "token-parity"
	}

	ctx, cancel := context.WithTimeout(context.Background(), time.Minute)
	defer cancel()
	cmd := subproc.CommandContext(ctx,
		esbuildBin,
		filepath.FromSlash(entryRel),
		"--bundle",
		"--format=esm",
		"--platform=node",
		"--minify",
		"--banner:js="+pluginGeneratedBanner,
	)
	cmd.Dir = repoRoot
	nodeModules := filepath.Join(repoRoot, "web", "node_modules")
	cmd.Env = append(os.Environ(), "NODE_PATH="+nodeModules)

	var stdout, stderr bytes.Buffer
	cmd.Stdout = &stdout
	cmd.Stderr = &stderr
	if runErr := cmd.Run(); runErr != nil {
		violations = append(violations, Violation{
			Rule:    "plugin-sync",
			File:    bundleRel,
			Message: fmt.Sprintf("esbuild failed while verifying %s: %v (%s)", bundleRel, runErr, strings.TrimSpace(stderr.String())),
		})
		return violations, len(moduleContents), "esbuild-error"
	}

	if !bytes.Equal(normalizeLF(stdout.Bytes()), normBundle) {
		violations = append(violations, Violation{
			Rule: "plugin-sync",
			File: bundleRel,
			Message: "internal/opencode/browser_plugin.mjs is out of sync with internal/opencode/*.js or web/src/policy/*.js; regenerate via: " +
				`NODE_PATH="$PWD/web/node_modules" web/node_modules/.bin/esbuild internal/opencode/browser_plugin.js --bundle --format=esm --platform=node --minify --banner:js='` +
				pluginGeneratedBanner + `' --outfile=internal/opencode/browser_plugin.mjs`,
		})
	}

	return violations, len(moduleContents), "esbuild-exact"
}

func collectPluginSourceClosure(repoRoot, entryRel string) (map[string]string, []Violation) {
	visited := make(map[string]string)
	var violations []Violation
	queue := []string{entryRel}

	for len(queue) > 0 {
		currRel := queue[0]
		queue = queue[1:]
		if _, seen := visited[currRel]; seen {
			continue
		}
		fullPath := filepath.Join(repoRoot, filepath.FromSlash(currRel))
		raw, err := os.ReadFile(fullPath)
		if err != nil {
			violations = append(violations, Violation{
				Rule:    "plugin-sync",
				File:    currRel,
				Message: fmt.Sprintf("referenced plugin module %s does not exist", currRel),
			})
			continue
		}
		src := string(raw)
		visited[currRel] = src

		matches := jsImportRe.FindAllStringSubmatch(src, -1)
		var next []string
		for _, m := range matches {
			if len(m) < 2 {
				continue
			}
			resolved := path.Clean(path.Join(path.Dir(currRel), m[1]))
			if _, seen := visited[resolved]; !seen {
				next = append(next, resolved)
			}
		}
		sort.Strings(next)
		queue = append(queue, next...)
	}
	return visited, violations
}

func verifyPluginSemanticTokens(bundleRel, bundleText string, modules map[string]string) []Violation {
	var violations []Violation

	if codeIdxSrc, ok := modules["internal/opencode/code_index_tool.js"]; ok {
		if m := jsIndexActionsRe.FindStringSubmatch(codeIdxSrc); len(m) >= 2 {
			for _, tok := range jsQuotedTokenRe.FindAllStringSubmatch(m[1], -1) {
				needle := `"` + tok[1] + `"`
				if !strings.Contains(bundleText, needle) {
					violations = append(violations, Violation{
						Rule:    "plugin-sync",
						File:    bundleRel,
						Message: fmt.Sprintf("bundle is missing hoxi_code_index action %s from code_index_tool.js", needle),
					})
				}
			}
		}
	}

	if pluginSrc, ok := modules["internal/opencode/hoxi_plugin.js"]; ok {
		if m := jsPluginToolsRe.FindStringSubmatch(pluginSrc); len(m) >= 2 {
			for _, tok := range jsObjectKeyRe.FindAllStringSubmatch(m[1], -1) {
				if !strings.Contains(bundleText, tok[1]+":") {
					violations = append(violations, Violation{
						Rule:    "plugin-sync",
						File:    bundleRel,
						Message: fmt.Sprintf("bundle is missing registered tool %q from hoxi_plugin.js", tok[1]),
					})
				}
			}
		}
	}

	if riskSrc, ok := modules["web/src/policy/external-path-risk.js"]; ok {
		if !strings.Contains(riskSrc, `".hoxi"`) || !strings.Contains(bundleText, `".hoxi"`) {
			violations = append(violations, Violation{
				Rule:    "plugin-sync",
				File:    bundleRel,
				Message: `protected ".hoxi" segment must remain present in both external-path-risk.js and browser_plugin.mjs`,
			})
		}
		if m := jsSensitiveSetRe.FindStringSubmatch(riskSrc); len(m) >= 2 {
			for _, tok := range jsQuotedTokenRe.FindAllStringSubmatch(m[1], -1) {
				needle := `"` + tok[1] + `"`
				if !strings.Contains(bundleText, needle) {
					violations = append(violations, Violation{
						Rule:    "plugin-sync",
						File:    bundleRel,
						Message: fmt.Sprintf("bundle is missing sensitive basename %s from web/src/policy/external-path-risk.js", needle),
					})
				}
			}
		}
	}

	return violations
}

func resolveLocalEsbuild(repoRoot string) string {
	binName := "esbuild"
	if runtime.GOOS == "windows" {
		binName = "esbuild.cmd"
	}
	candidate := filepath.Join(repoRoot, "web", "node_modules", ".bin", binName)
	info, err := os.Stat(candidate)
	if err != nil || info.IsDir() {
		return ""
	}
	return candidate
}

func normalizeLF(b []byte) []byte {
	return bytes.ReplaceAll(b, []byte("\r\n"), []byte("\n"))
}
